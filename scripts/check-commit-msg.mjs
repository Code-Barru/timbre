#!/usr/bin/env node
// Valide le message de commit contre la convention Conventional Commits.
// Exécuté par le hook prek `conventional-commit` (stage commit-msg).

import { readFileSync } from 'node:fs';

const TYPES = [
	'feat',
	'fix',
	'chore',
	'docs',
	'style',
	'refactor',
	'perf',
	'test',
	'build',
	'ci',
	'revert'
];

const PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9._/-]+\\))?!?: .{1,72}$`);
const AUTOGENERATED = /^(Merge |Revert |fixup! |squash! )/;

const path = process.argv[2];
if (!path) {
	console.error('check-commit-msg : chemin du fichier message manquant.');
	process.exit(1);
}

const subject = readFileSync(path, 'utf8')
	.split('\n')
	.find((line) => line.trim() !== '' && !line.startsWith('#'));

if (subject === undefined || AUTOGENERATED.test(subject)) process.exit(0);
if (PATTERN.test(subject)) process.exit(0);

console.error(`Message de commit invalide :\n  ${subject}\n`);
console.error('Format attendu : <type>(<scope facultatif>)!: <description>');
console.error(`Types : ${TYPES.join(', ')}`);
console.error('Description : 1 à 72 caractères.');
console.error('Exemple : feat(study): ajout du planning FSRS');
process.exit(1);
